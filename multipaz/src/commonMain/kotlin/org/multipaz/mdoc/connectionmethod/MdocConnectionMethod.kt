/**
 * Engagement context in which a `DeviceRetrievalMethod` CBOR structure is encoded or decoded.
 *
 * Reference: ISO/IEC 18013-5 Second Edition clauses 9.2, 9.3, 9.5, and 11.1.2.
 */
enum class MdocEngagementType {
    /**
     * Forward one-way engagement in a `DeviceEngagement` QR code (`mdoc:` URI).
     */
    DEVICE_QR,

    /**
     * Reverse one-way engagement in a `ReaderEngagement` QR code (`mdoc:` URI).
     */
    READER_QR,

    /**
     * NFC Concurrent Channel Engagement (CCE) `CCEHandoverRequest` sent from mdoc reader to mdoc.
     */
    CCE_REQUEST,

    /**
     * NFC Concurrent Channel Engagement (CCE) `CCEHandoverSelect` sent from mdoc to mdoc reader.
     */
    CCE_SELECT,
}

/**
 * NFC Forum Connection Handover context in which NDEF carrier records are encoded.
 *
 * Reference: ISO/IEC 18013-5 Second Edition clauses 9.4 and 11.1.3.
 */
enum class MdocNfcHandoverType {
    /**
     * NFC Static Handover `HandoverSelect` (`Hs`) message generated by an mdoc.
     */
    STATIC_HS,

    /**
     * NFC Negotiated Handover `HandoverRequest` (`Hr`) message generated by an mdoc reader.
     */
    NEGOTIATED_HR,

    /**
     * NFC Negotiated Handover `HandoverSelect` (`Hs`) message generated by an mdoc.
     */
    NEGOTIATED_HS,
}

/**
 * Bluetooth LE device address type according to Bluetooth Core Specification Supplement section 1.16.
 *
 * @property code the 1-byte wire value (`0x00` for public, `0x01` for random).
 */
enum class BleAddressType(val code: Int) {
    /**
     * Public Device Address (`0x00`).
     */
    PUBLIC(0x00),

    /**
     * Random Device Address (`0x01`).
     */
    RANDOM(0x01);

    companion object {
        /**
         * Resolves a [BleAddressType] from its 1-byte wire code.
         *
         * @param code the 1-byte address type code.
         * @return the corresponding [BleAddressType].
         * @throws IllegalArgumentException if [code] is not `0x00` or `0x01`.
         */
        fun fromCode(code: Int): BleAddressType =
            entries.find { it.code == code }
                ?: throw IllegalArgumentException("Invalid BLE address type code: $code")
    }
}

/**
 * Bluetooth LE Peripheral Device Address (`BD_ADDR` + address type) used in `BleOptions` key `20`
 * and BLE OOB AD type `0x1B` (Bluetooth Core Specification Supplement section 1.16).
 *
 * @property address the 6-byte Bluetooth MAC address in standard big-endian byte order
 *   (e.g. `11:22:33:44:55:66` is `ByteString(0x11, 0x22, 0x33, 0x44, 0x55, 0x66)`).
 * @property addressType whether [address] is a [BleAddressType.PUBLIC] or [BleAddressType.RANDOM] address.
 */
data class BlePeripheralAddress(
    val address: ByteString,
    val addressType: BleAddressType,
) {
    init {
        require(address.size == 6) {
            "BLE MAC address should be 6 bytes, got ${address.size}"
        }
    }

    /**
     * Encodes this address to the 7-byte Bluetooth CSS section 1.16 wire representation
     * (6-byte little-endian `BD_ADDR` followed by 1-byte address type).
     *
     * @return the 7-byte encoded peripheral address.
     */
    fun toEncoded(): ByteArray = byteArrayOf(
        address[5],
        address[4],
        address[3],
        address[2],
        address[1],
        address[0],
        addressType.code.toByte(),
    )

    override fun toString(): String {
        val hexDigits = "0123456789abcdef"
        val sb = StringBuilder()
        for (n in 0..5) {
            if (n > 0) {
                sb.append("-")
            }
            val value = address[n].toInt() and 0xff
            sb.append(hexDigits[value shr 4])
            sb.append(hexDigits[value and 0x0f])
        }
        sb.append("/")
        sb.append(addressType.name.lowercase())
        return sb.toString()
    }

    companion object {
        /**
         * Decodes a 7-byte Bluetooth CSS section 1.16 wire representation into a [BlePeripheralAddress].
         *
         * @param encoded the 7-byte encoded peripheral address (6-byte little-endian `BD_ADDR` + 1-byte type).
         * @return the decoded [BlePeripheralAddress].
         * @throws IllegalArgumentException if [encoded] is not 7 bytes or has an invalid address type.
         */
        fun fromEncoded(encoded: ByteArray): BlePeripheralAddress {
            require(encoded.size == 7) {
                "Encoded BLE peripheral address must be 7 bytes, got ${encoded.size}"
            }
            val bigEndianMac = ByteString(
                encoded[5],
                encoded[4],
                encoded[3],
                encoded[2],
                encoded[1],
                encoded[0],
            )
            val addressType = BleAddressType.fromCode(encoded[6].toInt() and 0xff)
            return BlePeripheralAddress(bigEndianMac, addressType)
        }
    }
}

/**
 * A single concrete device retrieval method and transport mode in ISO/IEC 18013-5.
 *
 * Each instance represents exactly one actionable transport mode (e.g., [Ble.GattPeripheral],
 * [Ble.DirectL2capCentral], [Nfc], [WifiAware], or [Http]). Wire-level coalescing of multiple
 * [Ble] modes into a single `[2, 1, BleOptions]` `DeviceRetrievalMethod` or BLE OOB + `ChBleOptions`
 * NDEF carrier is handled automatically by [encodeDeviceRetrievalMethods] and [encodeNdefHandoverCarriers],
 * and wire-level expansion back into ordered single-mode instances is handled by
 * [decodeDeviceRetrievalMethods] and [decodeNdefHandoverCarrier].
 */
sealed class MdocConnectionMethod {

    /**
     * Encodes this single connection method as `DeviceRetrievalMethod` CBOR.
     *
     * To encode multiple connection methods (automatically coalescing multiple [Ble] modes into one
     * `DeviceRetrievalMethod`), use [encodeDeviceRetrievalMethods].
     *
     * @param engagementType the engagement context controlling context-specific field rules and validation.
     * @return the encoded `DeviceRetrievalMethod` CBOR bytes.
     */
    fun toDeviceEngagement(
        engagementType: MdocEngagementType = MdocEngagementType.DEVICE_QR,
    ): ByteArray = Cbor.encode(encodeDeviceRetrievalMethods(listOf(this), engagementType).single())

    /**
     * Bluetooth Low Energy (BLE) connection methods according to ISO/IEC 18013-5 Second Edition clauses 11.1.1–11.1.3.
     *
     * Subtype names follow the mdoc-perspective CDDL identifiers from `BleOptions`:
     * - [GattPeripheral] (`0: GattPeripheral`): mdoc is BLE Peripheral / GATT server; mdoc reader is BLE Central / GATT client.
     * - [GattCentral] (`1: GattCentral`): mdoc is BLE Central / GATT client; mdoc reader is BLE Peripheral / GATT server.
     * - [DirectL2capPeripheral] (`2: DirectL2capPeripheral`): mdoc is BLE Peripheral / L2CAP server; mdoc reader is BLE Central / L2CAP client.
     * - [DirectL2capCentral] (`3: DirectL2capCentral`): mdoc is BLE Central / L2CAP client; mdoc reader is BLE Peripheral / L2CAP server.
     */
    sealed class Ble : MdocConnectionMethod() {
        /**
         * The 128-bit BLE service UUID for this mode, if known.
         */
        abstract val uuid: UUID?

        /**
         * The 7-byte BLE peripheral device address of whichever peer acts as BLE Peripheral in this mode, if known.
         */
        abstract val peripheralAddress: BlePeripheralAddress?

        /**
         * Whether the mdoc acts as BLE Peripheral (and the mdoc reader acts as BLE Central) in this mode.
         */
        val isMdocPeripheral: Boolean
            get() = this is GattPeripheral || this is DirectL2capPeripheral

        /**
         * Whether the mdoc acts as BLE Central (and the mdoc reader acts as BLE Peripheral) in this mode.
         */
        val isMdocCentral: Boolean
            get() = this is GattCentral || this is DirectL2capCentral

        /**
         * Whether this mode uses GATT for data transfer ([GattPeripheral] or [GattCentral]).
         */
        val isGatt: Boolean
            get() = this is GattPeripheral || this is GattCentral

        /**
         * Whether this mode uses direct BLE L2CAP for data transfer ([DirectL2capPeripheral] or [DirectL2capCentral]).
         */
        val isDirectL2cap: Boolean
            get() = this is DirectL2capPeripheral || this is DirectL2capCentral

        /**
         * The L2CAP PSM if this is a [DirectL2capPeripheral] or [DirectL2capCentral] with a known PSM, or `null`.
         */
        val directL2capPsm: Int?
            get() = when (this) {
                is DirectL2capPeripheral -> psm
                is DirectL2capCentral -> psm
                is GattPeripheral, is GattCentral -> null
            }

        /**
         * Returns a copy of this [Ble] connection method with its [uuid] replaced by [uuid].
         *
         * @param uuid the new service UUID, or `null`.
         * @return a copy of this [Ble] instance with the updated [uuid].
         */
        abstract fun withUuid(uuid: UUID?): Ble

        /**
         * mdoc GATT peripheral server mode (`BleOptions` key `0: GattPeripheral`).
         *
         * @property uuid the 128-bit BLE service UUID advertised by the mdoc, if known.
         * @property peripheralAddress the mdoc's BLE peripheral device address, if known.
         */
        data class GattPeripheral(
            override val uuid: UUID? = null,
            override val peripheralAddress: BlePeripheralAddress? = null,
        ) : Ble() {
            override fun withUuid(uuid: UUID?): GattPeripheral = copy(uuid = uuid)

            override fun toString(): String = buildString {
                append("ble:gatt_peripheral:uuid=$uuid")
                if (peripheralAddress != null) {
                    append(":addr=$peripheralAddress")
                }
            }
        }

        /**
         * mdoc GATT central client mode (`BleOptions` key `1: GattCentral`).
         *
         * @property uuid the 128-bit BLE service UUID advertised by the mdoc reader, if known.
         * @property peripheralAddress the mdoc reader's BLE peripheral device address, if known.
         */
        data class GattCentral(
            override val uuid: UUID? = null,
            override val peripheralAddress: BlePeripheralAddress? = null,
        ) : Ble() {
            override fun withUuid(uuid: UUID?): GattCentral = copy(uuid = uuid)

            override fun toString(): String = buildString {
                append("ble:gatt_central:uuid=$uuid")
                if (peripheralAddress != null) {
                    append(":addr=$peripheralAddress")
                }
            }
        }

        /**
         * mdoc direct BLE L2CAP peripheral mode (`BleOptions` key `2: DirectL2capPeripheral`).
         *
         * @property uuid the 128-bit BLE service UUID advertised by the mdoc, if known.
         * @property psm the L2CAP PSM of the mdoc's L2CAP server, if known.
         * @property peripheralAddress the mdoc's BLE peripheral device address, if known.
         */
        data class DirectL2capPeripheral(
            override val uuid: UUID? = null,
            val psm: Int? = null,
            override val peripheralAddress: BlePeripheralAddress? = null,
        ) : Ble() {
            override fun withUuid(uuid: UUID?): DirectL2capPeripheral = copy(uuid = uuid)

            override fun toString(): String = buildString {
                append("ble:direct_l2cap_peripheral:uuid=$uuid")
                if (psm != null) {
                    append(":psm=$psm")
                }
                if (peripheralAddress != null) {
                    append(":addr=$peripheralAddress")
                }
            }
        }

        /**
         * mdoc direct BLE L2CAP central mode (`BleOptions` key `3: DirectL2capCentral`).
         *
         * @property uuid the 128-bit BLE service UUID advertised by the mdoc reader, if known.
         * @property psm the L2CAP PSM of the mdoc reader's L2CAP server, if known.
         * @property peripheralAddress the mdoc reader's BLE peripheral device address, if known.
         */
        data class DirectL2capCentral(
            override val uuid: UUID? = null,
            val psm: Int? = null,
            override val peripheralAddress: BlePeripheralAddress? = null,
        ) : Ble() {
            override fun withUuid(uuid: UUID?): DirectL2capCentral = copy(uuid = uuid)

            override fun toString(): String = buildString {
                append("ble:direct_l2cap_central:uuid=$uuid")
                if (psm != null) {
                    append(":psm=$psm")
                }
                if (peripheralAddress != null) {
                    append(":addr=$peripheralAddress")
                }
            }
        }

        companion object {
            /**
             * The device retrieval method type for BLE according to ISO/IEC 18013-5 clause 9.2 / 11.1.2.
             */
            const val METHOD_TYPE = 2L

            /**
             * The supported version of the device retrieval method type for BLE.
             */
            const val METHOD_MAX_VERSION = 1L

            /**
             * Carrier data reference ID (`"0"`) for BLE OOB records in NFC Connection Handover.
             */
            const val CARRIER_DATA_REFERENCE_BLE = "0"

            /**
             * Auxiliary data reference ID (`"chble"`) for `ChBleOptions` records in NFC Connection Handover.
             */
            const val AUXILIARY_DATA_REFERENCE_CH_BLE_OPTIONS = "chble"
        }
    }

    /**
     * Near Field Communication (NFC) data retrieval connection method according to ISO/IEC 18013-5.
     *
     * @property commandDataFieldMaxLength the maximum length for the command data field.
     * @property responseDataFieldMaxLength the maximum length of the response data field.
     */
    data class Nfc(
        val commandDataFieldMaxLength: Long,
        val responseDataFieldMaxLength: Long,
    ) : MdocConnectionMethod() {
        override fun toString(): String =
            "nfc:cmd_max_length=$commandDataFieldMaxLength:resp_max_length=$responseDataFieldMaxLength"

        companion object {
            /**
             * The device retrieval method type for NFC according to ISO/IEC 18013-5.
             */
            const val METHOD_TYPE = 1L

            /**
             * The supported version of the device retrieval method type for NFC.
             */
            const val METHOD_MAX_VERSION = 1L

            /**
             * Carrier data reference ID (`"nfc"`) for NFC records in NFC Connection Handover.
             */
            const val CARRIER_DATA_REFERENCE_NFC = "nfc"
        }
    }

    /**
     * Wi-Fi Aware connection method according to ISO/IEC 18013-5.
     *
     * @property passphraseInfoPassphrase the passphrase or `null`.
     * @property channelInfoChannelNumber the channel number or `null`.
     * @property channelInfoOperatingClass the operating class or `null`.
     * @property bandInfoSupportedBands the supported bands or `null`.
     */
    data class WifiAware(
        val passphraseInfoPassphrase: String? = null,
        val channelInfoChannelNumber: Long? = null,
        val channelInfoOperatingClass: Long? = null,
        val bandInfoSupportedBands: ByteString? = null,
    ) : MdocConnectionMethod() {
        @OptIn(ExperimentalStdlibApi::class)
        override fun toString(): String = buildString {
            append("wifi_aware")
            if (passphraseInfoPassphrase != null) {
                append(":passphrase=$passphraseInfoPassphrase")
            }
            if (channelInfoChannelNumber != null) {
                append(":channel_info_channel_number=$channelInfoChannelNumber")
            }
            if (channelInfoOperatingClass != null) {
                append(":channel_info_operating_class=$channelInfoOperatingClass")
            }
            if (bandInfoSupportedBands != null) {
                append(":base_info_supported_bands=${bandInfoSupportedBands.toHexString()}")
            }
        }

        companion object {
            /**
             * The device retrieval method type for Wi-Fi Aware according to ISO/IEC 18013-5.
             */
            const val METHOD_TYPE = 3L

            /**
             * The supported version of the device retrieval method type for Wi-Fi Aware.
             */
            const val METHOD_MAX_VERSION = 1L
        }
    }

    /**
     * HTTP connection method according to ISO/IEC TS 18013-7:2024 Annex A.
     *
     * @property uri the server URI.
     */
    data class Http(
        val uri: String,
    ) : MdocConnectionMethod() {
        override fun toString(): String = "http:uri=$uri"

        companion object {
            /**
             * The device retrieval method type for HTTP according to ISO/IEC TS 18013-7:2024 Annex A.
             */
            const val METHOD_TYPE = 4L

            /**
             * The supported version of the device retrieval method type for HTTP.
             */
            const val METHOD_MAX_VERSION = 1L
        }
    }

    companion object {
        private const val TAG = "MdocConnectionMethod"

        /**
         * Encodes a list of single-mode [MdocConnectionMethod] entries into `DeviceRetrievalMethods` CBOR items,
         * coalescing all [Ble] entries into a single `[2, 1, BleOptions]` item at the position of the first [Ble]
         * entry (satisfying ISO/IEC 18013-5 clause 9.2's uniqueness rule for `(type, version)` tuples).
         *
         * @param methods the single-mode connection methods to encode.
         * @param engagementType the engagement context controlling context-specific field rules and validation.
         * @return the encoded `DeviceRetrievalMethod` CBOR [DataItem] elements.
         * @throws IllegalArgumentException if [methods] violates [engagementType] rules or contains conflicting
         *   parameters or duplicate non-BLE retrieval method types.
         */
        fun encodeDeviceRetrievalMethods(
            methods: List<MdocConnectionMethod>,
            engagementType: MdocEngagementType = MdocEngagementType.DEVICE_QR,
        ): List<DataItem> {
            if (engagementType == MdocEngagementType.CCE_SELECT) {
                require(methods.size <= 1) {
                    "At most one connection method may be selected in CCE_SELECT, got ${methods.size}"
                }
            }
            require(methods.count { it is Nfc } <= 1) {
                "At most one NFC connection method may be encoded in DeviceRetrievalMethods"
            }
            require(methods.count { it is WifiAware } <= 1) {
                "At most one WifiAware connection method may be encoded in DeviceRetrievalMethods"
            }
            require(methods.count { it is Http } <= 1) {
                "At most one Http connection method may be encoded in DeviceRetrievalMethods"
            }

            val bleMethods = methods.filterIsInstance<Ble>()
            var bleEmitted = false
            val result = mutableListOf<DataItem>()
            for (method in methods) {
                when (method) {
                    is Ble -> {
                        if (!bleEmitted) {
                            result.add(encodeBleDeviceRetrievalMethod(bleMethods, engagementType))
                            bleEmitted = true
                        }
                    }
                    is Nfc -> result.add(encodeNfcDeviceRetrievalMethod(method, engagementType))
                    is WifiAware -> result.add(encodeWifiAwareDeviceRetrievalMethod(method, engagementType))
                    is Http -> result.add(encodeHttpDeviceRetrievalMethod(method, engagementType))
                }
            }
            return result
        }

        /**
         * Decodes a list of `DeviceRetrievalMethod` CBOR [DataItem] elements into single-mode
         * [MdocConnectionMethod] instances.
         *
         * Any multi-mode `BleOptions` item is expanded in preference order:
         * [Ble.DirectL2capCentral], [Ble.DirectL2capPeripheral], [Ble.GattCentral], [Ble.GattPeripheral],
         * with `PeripheralAddress` (`20`) and `DirectL2capPSM` (`21`) attached only to [senderRole]'s
         * BLE Peripheral modes.
         *
         * @param items the `DeviceRetrievalMethod` CBOR array items.
         * @param senderRole the [MdocRole] of the peer that authored the engagement structure
         *   ([MdocRole.MDOC] for `DeviceEngagement`, [MdocRole.MDOC_READER] for `ReaderEngagement`).
         * @return the decoded single-mode [MdocConnectionMethod] instances.
         * @throws IllegalArgumentException if any item's CBOR structure is malformed.
         */
        fun decodeDeviceRetrievalMethods(
            items: List<DataItem>,
            senderRole: MdocRole = MdocRole.MDOC,
        ): List<MdocConnectionMethod> {
            val result = mutableListOf<MdocConnectionMethod>()
            for (item in items) {
                val type = item[0].asNumber
                when (type) {
                    Nfc.METHOD_TYPE -> decodeNfcDeviceRetrievalMethod(item)?.let { result.add(it) }
                    Ble.METHOD_TYPE -> result.addAll(decodeBleDeviceRetrievalMethod(item, senderRole))
                    WifiAware.METHOD_TYPE -> decodeWifiAwareDeviceRetrievalMethod(item)?.let { result.add(it) }
                    Http.METHOD_TYPE -> decodeHttpDeviceRetrievalMethod(item)?.let { result.add(it) }
                    else -> Logger.w(TAG, "Unsupported ConnectionMethod type $type in DeviceEngagement")
                }
            }
            return result
        }

        /**
         * Decodes a single `DeviceRetrievalMethod` CBOR byte array into one or more single-mode
         * [MdocConnectionMethod] instances (or an empty list if the method type/version is unsupported).
         *
         * @param encodedDeviceRetrievalMethod the bytes of `DeviceRetrievalMethod` CBOR.
         * @param senderRole the [MdocRole] of the peer that authored the `DeviceRetrievalMethod`.
         * @return the decoded single-mode [MdocConnectionMethod] instances.
         * @throws IllegalArgumentException if the given CBOR is malformed.
         */
        fun fromDeviceEngagement(
            encodedDeviceRetrievalMethod: ByteArray,
            senderRole: MdocRole = MdocRole.MDOC,
        ): List<MdocConnectionMethod> =
            decodeDeviceRetrievalMethods(listOf(Cbor.decode(encodedDeviceRetrievalMethod)), senderRole)

        /**
         * Encodes a list of single-mode [MdocConnectionMethod] entries into NFC Forum Connection Handover
         * [HandoverCarrierRecords] bundles, coalescing all [Ble] entries into a single BLE OOB (`"0"`) +
         * optional `ChBleOptions` (`"chble"`) carrier at the position of the first [Ble] entry.
         *
         * Unsupported NFC handover methods ([WifiAware], [Http]) are skipped with a warning.
         *
         * @param methods the single-mode connection methods to encode.
         * @param handoverType the NFC Connection Handover message context ([MdocNfcHandoverType.STATIC_HS],
         *   [MdocNfcHandoverType.NEGOTIATED_HR], or [MdocNfcHandoverType.NEGOTIATED_HS]).
         * @param sharedAuxiliaryReferences shared auxiliary data references (e.g. `"mdoc"` or `"mdocreader"`)
         *   to attach to every carrier's `"ac"` record.
         * @param hrHadChBleOptions when [handoverType] is [MdocNfcHandoverType.NEGOTIATED_HS], whether the
         *   incoming `HandoverRequest` included a `"chble"` record (causing `ChBleOptions` to be echoed
         *   when a BLE mode is selected, per ISO/IEC 18013-5 Second Edition clause 11.1.3).
         * @return the encoded [HandoverCarrierRecords] bundles in carrier order.
         * @throws IllegalArgumentException if [methods] violates [handoverType] rules or has conflicting parameters.
         */
        fun encodeNdefHandoverCarriers(
            methods: List<MdocConnectionMethod>,
            handoverType: MdocNfcHandoverType,
            sharedAuxiliaryReferences: List<String> = emptyList(),
            hrHadChBleOptions: Boolean = false,
        ): List<HandoverCarrierRecords> {
            if (handoverType == MdocNfcHandoverType.NEGOTIATED_HS) {
                require(methods.size == 1) {
                    "Exactly one connection method must be selected in NEGOTIATED_HS, got ${methods.size}"
                }
            }
            require(methods.count { it is Nfc } <= 1) {
                "At most one NFC connection method may be encoded in NFC Connection Handover"
            }

            val bleMethods = methods.filterIsInstance<Ble>()
            var bleEmitted = false
            val result = mutableListOf<HandoverCarrierRecords>()
            for (method in methods) {
                when (method) {
                    is Ble -> {
                        if (!bleEmitted) {
                            result.add(
                                encodeBleNdefHandoverCarrier(
                                    bleMethods = bleMethods,
                                    handoverType = handoverType,
                                    sharedAuxiliaryReferences = sharedAuxiliaryReferences,
                                    hrHadChBleOptions = hrHadChBleOptions,
                                )
                            )
                            bleEmitted = true
                        }
                    }
                    is Nfc -> result.add(
                        encodeNfcNdefHandoverCarrier(
                            nfc = method,
                            sharedAuxiliaryReferences = sharedAuxiliaryReferences,
                        )
                    )
                    is WifiAware, is Http -> {
                        Logger.w(TAG, "NFC Connection Handover is not supported for $method")
                    }
                }
            }
            return result
        }

        /**
         * Decodes an NFC Connection Handover carrier configuration [NdefRecord] into zero or more
         * single-mode [MdocConnectionMethod] instances.
         *
         * Auxiliary data records (`"mdoc"`, `"mdocreader"`, `"chble"`) return `emptyList()` when passed as
         * [record]. Multi-mode BLE OOB + `ChBleOptions` records expand in preference order:
         * [Ble.DirectL2capCentral], [Ble.DirectL2capPeripheral], [Ble.GattCentral], [Ble.GattPeripheral].
         *
         * @param record the candidate carrier configuration [NdefRecord].
         * @param senderRole the [MdocRole] of the peer that authored the NDEF message
         *   ([MdocRole.MDOC] for `HandoverSelect`, [MdocRole.MDOC_READER] for `HandoverRequest`).
         * @param fallbackUuid fallback BLE service UUID to use when the BLE OOB record omits `0x07` UUID.
         * @param auxiliaryRecords auxiliary data records referenced by this carrier's `"ac"` record.
         * @return the decoded single-mode [MdocConnectionMethod] instances, or `emptyList()` if [record]
         *   is an auxiliary or unsupported record.
         */
        fun decodeNdefHandoverCarrier(
            record: NdefRecord,
            senderRole: MdocRole,
            fallbackUuid: UUID?,
            auxiliaryRecords: List<NdefRecord> = emptyList(),
        ): List<MdocConnectionMethod> {
            if (record.tnf == NdefRecord.Tnf.MIME_MEDIA &&
                record.type.decodeToString() == NfcConst.MIME_TYPE_CONNECTION_HANDOVER_BLE &&
                record.id.decodeToString() == Ble.CARRIER_DATA_REFERENCE_BLE
            ) {
                return decodeBleNdefHandoverCarrier(record, senderRole, fallbackUuid, auxiliaryRecords)
            } else if (record.tnf == NdefRecord.Tnf.EXTERNAL_TYPE &&
                record.type.decodeToString() == NfcConst.EXTERNAL_TYPE_ISO_18013_5_NFC &&
                record.id.decodeToString() == Nfc.CARRIER_DATA_REFERENCE_NFC
            ) {
                return listOfNotNull(decodeNfcNdefHandoverCarrier(record))
            } else if (record.tnf == NdefRecord.Tnf.EXTERNAL_TYPE) {
                val externalType = record.type.decodeToString()
                if (externalType == NfcConst.EXTERNAL_TYPE_ISO_18013_5_DEVICE_ENGAGEMENT ||
                    externalType == NfcConst.EXTERNAL_TYPE_ISO_18013_5_READER_ENGAGEMENT ||
                    externalType == NfcConst.EXTERNAL_TYPE_ISO_18013_5_CH_BLE_OPTIONS
                ) {
                    // Auxiliary data records are not standalone connection methods.
                    return emptyList()
                }
            }
            Logger.w(TAG, "No support for NDEF record $record")
            return emptyList()
        }
    }
